inline long cpu_ms(const struct rusage& a, const struct rusage& b) {
  long us = (b.ru_utime.tv_sec - a.ru_utime.tv_sec) * 1000000L +
            (b.ru_utime.tv_usec - a.ru_utime.tv_usec) +
            (b.ru_stime.tv_sec - a.ru_stime.tv_sec) * 1000000L +
            (b.ru_stime.tv_usec - a.ru_stime.tv_usec);
  return us / 1000L;
}

inline std::string json_escape(const std::string& s) {
  std::string o;
  o.reserve(s.size() + 8);
  for (unsigned char c : s) {
    if (c == '"') o += "\\\"";
    else if (c == '\\') o += "\\\\";
    else if (c == '\n') o += "\\n";
    else if (c == '\t') o += "\\t";
    else if (c == '\r') o += "\\r";
    else if (c < 0x20) {
      char b[8];
      std::snprintf(b, sizeof b, "\\u%04x", c);
      o += b;
    } else o += static_cast<char>(c);
  }
  return o;
}

inline std::string ser(bool v) { return v ? "true" : "false"; }
inline std::string ser(const std::string& v) { return v; }
inline std::string ser(const char* v) { return v ? v : ""; }
template <typename T> inline std::string ser(const T& v) {
  std::ostringstream os;
  os << v;
  return os.str();
}
template <typename T> inline std::string ser(const std::vector<T>& v) {
  std::ostringstream os;
  os << "[";
  for (size_t i = 0; i < v.size(); ++i) {
    if (i) os << ", ";
    os << ser(v[i]);
  }
  os << "]";
  return os.str();
}

inline std::string trim(const std::string& s) {
  size_t b = 0, e = s.size();
  while (b < e && isspace(static_cast<unsigned char>(s[b]))) ++b;
  while (e > b && isspace(static_cast<unsigned char>(s[e - 1]))) --e;
  return s.substr(b, e - b);
}

// 比较：trim + 数组空白归一 + 浮点 1e-6（§5.3）
inline bool looks_number(const std::string& s) {
  if (s.empty()) return false;
  char* end = nullptr;
  std::strtod(s.c_str(), &end);
  return end && *end == '\0';
}
inline bool compare(const std::string& out, const std::string& exp) {
  const std::string a = trim(out);
  const std::string b = trim(exp);
  if (a == b) return true;
  if (looks_number(a) && looks_number(b)) {
    double x = std::strtod(a.c_str(), nullptr);
    double y = std::strtod(b.c_str(), nullptr);
    return std::fabs(x - y) <= 1e-6;
  }
  // 数组形态：按逗号切分后逐元素 trim 比较
  auto split = [](const std::string& t) {
    std::vector<std::string> parts;
    std::string cur;
    for (char c : t) {
      if (c == ',') { parts.push_back(trim(cur)); cur.clear(); }
      else cur += c;
    }
    parts.push_back(trim(cur));
    return parts;
  };
  if (a.find('[') != std::string::npos || b.find('[') != std::string::npos) {
    auto pa = split(a);
    auto pb = split(b);
    if (pa.size() != pb.size()) return false;
    for (size_t i = 0; i < pa.size(); ++i) {
      if (pa[i] != pb[i]) {
        if (looks_number(pa[i]) && looks_number(pb[i])) {
          if (std::fabs(std::strtod(pa[i].c_str(), nullptr) -
                        std::strtod(pb[i].c_str(), nullptr)) > 1e-6)
            return false;
        } else return false;
      }
    }
    return true;
  }
  return false;
}

