std::string json_to_cpp_literal(const nlohmann::json& value, const std::string& cpp_type,
                                std::string* reason) {
  const model::CppTypeShape shape = model::analyze_cpp_type(cpp_type);
  if (!shape.well_formed) {
    if (reason) *reason = "无法解析的 C++ 类型: " + cpp_type;
    return {};
  }
  std::string out;
  if (!literal_from_json(value, shape, shape.vector_depth, &out, reason)) return {};
  return out;
}

GenerateResult generate_harness(const model::ProblemBundle& problem) {
  GenerateResult r;
  if (problem.method_name.empty() || problem.signature.empty()) {
    r.error = "题库缺少 signature/method_name";
    return r;
  }
  if (problem.params.empty() || problem.cases.empty()) {
    r.error = "题库 params/cases 为空";
    return r;
  }
  // 生成期类型校验 §4.2.1：失败 → JE，不产出文件
  for (std::size_t ci = 0; ci < problem.cases.size(); ++ci) {
    const model::ProblemCase& c = problem.cases[ci];
    if (!c.args.is_array() || c.args.size() != problem.params.size()) {
      r.error = "cases[" + std::to_string(ci) + "].args 数量与 params 不符";
      return r;
    }
    for (std::size_t pi = 0; pi < problem.params.size(); ++pi) {
      if (model::is_expr_value(c.args[pi])) continue;
      const model::JsonShape js = model::analyze_json(c.args[pi]);
      const model::CppTypeShape cs = model::analyze_cpp_type(problem.params[pi].cpp_type);
      if (!js.is_expr && js.array_depth != cs.vector_depth) {
        r.error = "cases[" + std::to_string(ci) + "].args[" + std::to_string(pi) +
                  "] 容器深度与形参类型不符";
        return r;
      }
    }
    if (model::is_expr_value(c.expected) && problem.harness_prelude.empty()) {
      r.error = "cases[" + std::to_string(ci) + "] 使用 __expr 但 harness_prelude 为空";
      return r;
    }
  }
  const model::CppTypeShape ret_shape = model::analyze_cpp_type(problem.return_type);
  for (const model::ProblemCase& c : problem.cases) {
    if (model::is_expr_value(c.expected)) continue;
    const model::JsonShape js = model::analyze_json(c.expected);
    if (!js.is_expr && js.array_depth != ret_shape.vector_depth) {
      r.error = "expected 容器深度与 return_type 不符";
      return r;
    }
  }

  // solution_decl 自带标准头：tester.cpp 先 include 它，签名里的
  // std::vector/std::string 必须能解析（题库签名本身不带 #include）
  r.solution_decl = "#include <string>\n#include <vector>\n\n" + problem.signature + "\n";
  r.tester_util = kTesterUtil;

  std::ostringstream tp;
  tp << "// generated tester for " << problem.slug << "\n";
  tp << "#include \"solution_decl.h\"\n";
  tp << "#include \"tester_util.h\"\n";
  if (!problem.harness_prelude.empty()) tp << problem.harness_prelude << "\n";
  tp << "\nint main(int argc, char** argv) {\n";
  tp << "  if (argc < 2) return 2;\n";
  tp << "  const int idx = std::atoi(argv[1]);\n";
  tp << "  Solution sol;\n";
  tp << "  struct rusage r0{}, r1{};\n";
  tp << "  switch (idx) {\n";

  for (const model::ProblemCase& c : problem.cases) {
    tp << "  case " << c.case_idx << ": {\n";
    std::string args_text;
    for (std::size_t pi = 0; pi < problem.params.size(); ++pi) {
      const model::ProblemParam& p = problem.params[pi];
      std::string reason;
      std::string lit = json_to_cpp_literal(c.args[pi], p.cpp_type, &reason);
      if (lit.empty()) {
        r.error = "cases[" + std::to_string(c.case_idx) + "].args[" + std::to_string(pi) +
                  "]: " + reason;
        return r;
      }
      tp << "    " << decl_type(p.cpp_type) << " " << p.name << " = " << lit << ";\n";
      if (pi) args_text += ", ";
      args_text += p.name + "=" + c.args[pi].dump();
    }
    std::string exp_reason;
    std::string exp_lit;
    if (model::is_expr_value(c.expected)) {
      exp_lit = c.expected.at("__expr").get<std::string>();
    } else {
      exp_lit = json_to_cpp_literal(c.expected, problem.return_type, &exp_reason);
      if (exp_lit.empty()) {
        r.error = "expected: " + exp_reason;
        return r;
      }
    }
    // expected 序列化用常量字符串（比较走 harness）
    const std::string exp_text = c.expected.is_string() && !model::is_expr_value(c.expected)
                                     ? c.expected.get<std::string>()
                                     : c.expected.dump();
    std::string call_args;
    for (std::size_t pi = 0; pi < problem.params.size(); ++pi) {
      if (pi) call_args += ", ";
      call_args += problem.params[pi].name;
    }
    tp << "    getrusage(RUSAGE_SELF, &r0);\n";
    tp << "    auto __ret = sol." << problem.method_name << "(" << call_args << ");\n";
    tp << "    getrusage(RUSAGE_SELF, &r1);\n";
    tp << "    const std::string __out = ojtest::ser(__ret);\n";
    tp << "    const std::string __exp = \"" << escape_cpp_string(exp_text) << "\";\n";
    tp << "    const bool __passed = ojtest::compare(__out, __exp);\n";
    tp << "    ojtest::emit(" << c.case_idx << ", \"" << escape_cpp_string(c.brief) << "\", \""
       << escape_cpp_string(args_text) << "\", __out, __exp,\n";
    tp << "                 ojtest::cpu_ms(r0, r1), (long)r1.ru_maxrss, __passed, \"\");\n";
    tp << "    return 0;\n";
    tp << "  }\n";
  }
  tp << "  default: return 3;\n";
  tp << "  }\n}\n";

  r.tester_cpp = tp.str();
  r.ok = true;
  return r;
}

