std::string escape_cpp_string(const std::string& text) {
  std::string out;
  out.reserve(text.size() + 8);
  for (unsigned char c : text) {
    switch (c) {
      case '"': out += "\\\""; break;
      case '\\': out += "\\\\"; break;
      case '\n': out += "\\n"; break;
      case '\t': out += "\\t"; break;
      case '\r': out += "\\r"; break;
      default:
        if (c < 0x20 || c >= 0x80) {
          char buf[8];
          std::snprintf(buf, sizeof buf, "\\x%02X", c);
          out += buf;
        } else {
          out += static_cast<char>(c);
        }
    }
  }
  return out;
}

// 递归构造嵌套 vector 字面量。shape 来自 analyze_cpp_type。
bool literal_from_json(const nlohmann::json& value, const model::CppTypeShape& shape,
                       int depth_left, std::string* out, std::string* reason) {
  if (model::is_expr_value(value)) {
    *out = value.at("__expr").get<std::string>();
    return true;
  }
  if (depth_left > 0) {
    if (!value.is_array()) {
      if (reason) *reason = "期望数组，实际 " + std::string(value.type_name());
      return false;
    }
    std::ostringstream os;
    // 重建完整容器类型名：base 重复 depth_left 层（层树不能多写一层，
    // 否则生成 std::vector<std::vector<int>>{...} 无法赋给 vector<int> 形参）
    std::string inner = shape.base_type.empty() ? "int" : shape.base_type;
    for (int i = 0; i < depth_left; ++i) os << "std::vector<";
    os << inner;
    for (int i = 0; i < depth_left; ++i) os << ">";
    os << "{";
    bool first = true;
    for (const auto& item : value) {
      if (!first) os << ", ";
      first = false;
      std::string piece;
      if (!literal_from_json(item, shape, depth_left - 1, &piece, reason)) return false;
      os << piece;
    }
    os << "}";
    *out = os.str();
    return true;
  }
  // 叶子
  if (shape.base_type == "std::string" || shape.base_type == "string") {
    if (!value.is_string()) {
      if (reason) *reason = "期望字符串";
      return false;
    }
    *out = "std::string(\"" + escape_cpp_string(value.get<std::string>()) + "\")";
    return true;
  }
  if (shape.base_type == "bool") {
    if (!value.is_boolean()) {
      if (reason) *reason = "期望布尔";
      return false;
    }
    *out = value.get<bool>() ? "true" : "false";
    return true;
  }
  if (value.is_boolean()) {
    *out = value.get<bool>() ? "true" : "false";
    return true;
  }
  if (value.is_number_integer() || value.is_number_unsigned()) {
    *out = value.dump();
    return true;
  }
  if (value.is_number_float()) {
    *out = value.dump();
    return true;
  }
  if (value.is_string()) {
    *out = "\"" + escape_cpp_string(value.get<std::string>()) + "\"";
    return true;
  }
  if (value.is_null()) {
    *out = "nullptr";
    return true;
  }
  if (reason) *reason = "无法转成 C++ 字面量的 JSON 类型";
  return false;
}

// 去掉引用/const，得到声明用类型
std::string decl_type(const std::string& cpp_type) {
  std::string t;
  for (char c : cpp_type) {
    if (c == '&' || c == '*') continue;
    t += c;
  }
  // trim
  while (!t.empty() && std::isspace(static_cast<unsigned char>(t.front()))) t.erase(t.begin());
  while (!t.empty() && std::isspace(static_cast<unsigned char>(t.back()))) t.pop_back();
  return t.empty() ? "int" : t;
}

